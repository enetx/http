//go:build ignore

// Regenerate public aliases without copying the native protocol implementation.
package main

import (
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
)

func main() {
	var b strings.Builder
	b.WriteString("// Code generated by go generate; DO NOT EDIT.\n\npackage http2\n\nimport native \"github.com/enetx/http/internal/http2\"\n\n")
	for _, name := range []string{"frame.go", "errors.go", "http2.go"} {
		f, err := parser.ParseFile(token.NewFileSet(), filepath.Join("..", "internal", "http2", name), nil, 0)
		if err != nil {
			panic(err)
		}
		for _, decl := range f.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok {
				continue
			}
			for _, spec := range gen.Specs {
				switch spec := spec.(type) {
				case *ast.TypeSpec:
					if ast.IsExported(spec.Name.Name) {
						fmt.Fprintf(&b, "type %s = native.%s\n", spec.Name.Name, spec.Name.Name)
					}
				case *ast.ValueSpec:
					if gen.Tok != token.CONST {
						continue
					}
					for _, name := range spec.Names {
						if ast.IsExported(name.Name) {
							fmt.Fprintf(&b, "const %s = native.%s\n", name.Name, name.Name)
						}
					}
				}
			}
		}
	}
	result, err := format.Source([]byte(b.String()))
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("frame_aliases.go", result, 0644); err != nil {
		panic(err)
	}
}
